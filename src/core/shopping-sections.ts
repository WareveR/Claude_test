const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Keyword patterns in section order, each a whole word or phrase with an optional plural. */
const PATTERNS: [ShoppingSection, RegExp][] = KEYWORDS.map(([section, words]) => [
  section,
  new RegExp(`(?:^| )(?:${words.map(escape).join("|")})(?:s|es)?(?= |$)`),
]);

/**
 * The section an item belongs to, worked out from its name alone; case and accents don't
 * matter. A name no keyword matches is "other".
 */
export function shoppingSection(name: string): ShoppingSection {
  const folded = foldName(name);
  for (const [section, pattern] of PATTERNS) if (pattern.test(folded)) return section;
  return "other";
}
